const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const jiti = require('jiti')(__filename, { alias: { '@': root } })
const { profileSchema, linkSchema, orderLinks, clickHref, normalizeHandle, showBadge, socialsSchema, publicPath } = jiti('../lib/linkinbio/core.ts')
const { TOOL_IDS, getTool, isProtectedPath } = jiti('../tools/registry.ts')

test('linkinbio is a registry tool; /u stays public', () => {
  assert.ok(TOOL_IDS.includes('linkinbio')); assert.equal(getTool('linkinbio').route, '/links')
  assert.ok(isProtectedPath('/links')); assert.ok(!isProtectedPath('/u/someone'))
})
test('profile + link validation', () => {
  assert.equal(profileSchema.parse({ handle: '@Cooper', display_name: '', bio: '', avatar_url: '', show_funnels: true, published: true, theme: 'light', socials: {}, hide_badge: false }).handle, 'cooper')
  assert.equal(profileSchema.safeParse({ handle: 'ab', display_name: '', bio: '', avatar_url: '', show_funnels: true, published: true, theme: 'light', socials: {}, hide_badge: false }).success, false)
  assert.equal(profileSchema.safeParse({ handle: 'abc', display_name: '', bio: '', avatar_url: 'http://x', show_funnels: true, published: true, theme: 'light', socials: {}, hide_badge: false }).success, false)
  assert.ok(linkSchema.safeParse({ title: 'Site', url: 'https://saasnation.site' }).success)
  assert.equal(linkSchema.safeParse({ title: 'x', url: 'javascript:alert(1)' }).success, false)
  assert.equal(normalizeHandle(' @A_b '), 'a_b')
  assert.deepEqual(socialsSchema.parse({ instagram: 'https://instagram.com/x', evil: 'https://e', x: '' }), { instagram: 'https://instagram.com/x' })
  assert.equal(socialsSchema.safeParse({ github: 'javascript:1' }).success, false)
})
test('badge: hidden only with All Access + opt-out', () => {
  assert.equal(showBadge(false, false), true); assert.equal(showBadge(true, false), true)
  assert.equal(showBadge(false, true), true); assert.equal(showBadge(true, true), false)
  assert.equal(publicPath('coop'), '/@coop')
  const cfg = fs.readFileSync(path.join(root, 'next.config.mjs'), 'utf8'); assert.match(cfg, /source: '\/@:handle', destination: '\/u\/:handle'/)
  const sql = fs.readFileSync(path.join(root, 'supabase/migrations/20261024_linkinbio.sql'), 'utf8'); assert.match(sql, />= 12/)
})
test('ordering and click URLs', () => {
  assert.deepEqual(orderLinks([{ position: 2 }, { position: 0 }, { position: 1 }]).map((l) => l.position), [0, 1, 2])
  assert.equal(clickHref('coop', 'abc'), '/u/coop/l/abc')
})
test('migration: allowed tools extended, owner RLS, click fn service-only, no deletes of data', () => {
  const sql = fs.readFileSync(path.join(root, 'supabase/migrations/20261024_linkinbio.sql'), 'utf8')
  assert.match(sql, /'funnels', 'invoices', 'linkinbio', 'all'/)
  assert.match(sql, /enable row level security/); assert.match(sql, /grant execute on function public.lib_record_click\(text, uuid\) to service_role/)
  assert.doesNotMatch(sql, /delete from|truncate|drop table/i)
  const page = fs.readFileSync(path.join(root, 'app/u/[handle]/page.tsx'), 'utf8')
  assert.match(page, /page.badge &&/); assert.match(page, /Made with SaaS Nation/); assert.match(page, /href="\/pricing"/)
})

test('link-in-bio included with any paid plan; not sold separately', () => {
  const reg = jiti('../tools/registry.ts')
  assert.ok(reg.isIncludedTool('linkinbio')); assert.ok(!reg.isIncludedTool('invoices'))
  assert.ok(!reg.SOLD_ACCESS_KEYS.includes('linkinbio')); assert.ok(reg.SOLD_ACCESS_KEYS.includes('all'))
  const { parsePriceMap } = jiti('../lib/stripe-webhook.ts')
  assert.throws(() => parsePriceMap(JSON.stringify({ price_x: { tool: 'linkinbio' } })))
  const sql = fs.readFileSync(path.join(root, 'supabase/migrations/20261024_linkinbio_included.sql'), 'utf8')
  assert.match(sql, /where user_id = uid and active\)/)
  assert.match(fs.readFileSync(path.join(root, 'lib/access.ts'), 'utf8'), /isIncludedTool\(tool\)/)
  assert.match(fs.readFileSync(path.join(root, 'components/tools/tools-list.tsx'), 'utf8'), /filter\(\(t\) => !t\.includedWithAnyPlan\)/)
})
