const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const jiti = require('jiti')(__filename, { alias: { '@': root } })
const { legacyHostRedirect } = jiti('../lib/legacy-host.ts')
const { getTool, isProtectedPath } = jiti('../tools/registry.ts')

test('funnels.saasnation.site 301s to saasnation.site, same path + query', () => {
  assert.equal(legacyHostRedirect('funnels.saasnation.site', '/f/my-funnel', '?a=1'), 'https://saasnation.site/f/my-funnel?a=1')
  assert.equal(legacyHostRedirect('FUNNELS.saasnation.site:443', '/', ''), 'https://saasnation.site/')
  assert.equal(legacyHostRedirect('funnels.saasnation.site, proxy', '/dashboard', ''), 'https://saasnation.site/dashboard')
})
test('webhook + healthz keep working on both hosts; other hosts untouched', () => {
  assert.equal(legacyHostRedirect('funnels.saasnation.site', '/api/stripe/webhook', ''), null)
  assert.equal(legacyHostRedirect('funnels.saasnation.site', '/healthz', ''), null)
  assert.equal(legacyHostRedirect('saasnation.site', '/f/x', ''), null)
  assert.equal(legacyHostRedirect(null, '/', ''), null)
  const mw = fs.readFileSync(path.join(root, 'middleware.ts'), 'utf8')
  assert.match(mw, /legacyHostRedirect\(/); assert.match(mw, /NextResponse\.redirect\(legacy, 301\)/)
})
test('funnels tool under /funnels, old dashboard paths redirect, public pages unchanged', () => {
  assert.equal(getTool('funnels').route, '/funnels'); assert.equal(getTool('funnels').name, 'Funnel Maker')
  assert.ok(isProtectedPath('/funnels/abc')); assert.ok(!isProtectedPath('/f/abc'))
  for (const f of ['app/funnels/page.tsx', 'app/funnels/[funnelId]/page.tsx', 'app/funnels/templates/page.tsx', 'app/f']) assert.ok(fs.existsSync(path.join(root, f)), f)
  const cfg = fs.readFileSync(path.join(root, 'next.config.mjs'), 'utf8')
  assert.match(cfg, /source: '\/dashboard\/funnels\/:path\*', destination: '\/funnels\/:path\*'/)
  assert.match(cfg, /source: '\/dashboard\/templates', destination: '\/funnels\/templates'/)
})
test('branded SaaS Nation with saasnation.site default', () => {
  assert.match(fs.readFileSync(path.join(root, 'lib/auth-urls.ts'), 'utf8'), /'https:\/\/saasnation\.site'/)
  assert.match(fs.readFileSync(path.join(root, 'app/layout.tsx'), 'utf8'), /SaaS Nation/)
  assert.match(fs.readFileSync(path.join(root, 'components/nav/navbar.tsx'), 'utf8'), /SaaS Nation/)
  assert.match(fs.readFileSync(path.join(root, 'lib/site.ts'), 'utf8'), /PRODUCT = 'SaaS Nation'/)
})
