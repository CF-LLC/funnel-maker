test('claims: redirect key or access code; draft, no link or no files never unlock', () => {
  const base = { published: true, hasLink: true, files: 2, redirectKey: K, codeHash: hashCode('focus-2026'), hash: hashCode }
  assert.deepEqual(core.claimCheck({ ...base, key: K }), { ok: true, via: 'redirect' })
  assert.deepEqual(core.claimCheck({ ...base, key: K.toUpperCase() }), { ok: true, via: 'redirect' })
  assert.deepEqual(core.claimCheck({ ...base, code: ' FOCUS-2026 ' }), { ok: true, via: 'code' })
  assert.equal(core.claimCheck({ ...base, code: 'WRONG-1' }).ok, false)
  assert.equal(core.claimCheck({ ...base, key: '0b7d9f2e-5a1c-4e3b-9d8f-000000000000' }).ok, false)
  assert.equal(core.claimCheck({ ...base, codeHash: null, code: 'FOCUS-2026' }).ok, false)
  assert.equal(core.claimCheck({ ...base, published: false, key: K }).ok, false)
  assert.equal(core.claimCheck({ ...base, hasLink: false, key: K }).ok, false)
  assert.equal(core.claimCheck({ ...base, files: 0, key: K }).ok, false)
  assert.equal(core.claimCheck({ ...base }).ok, false)
  assert.match(hashCode('abcd'), /^[0-9a-f]{64}$/); assert.equal(hashCode('abcd'), hashCode(' ABCD '))
})
test('order state: revoked, expired, used up', () => {
  const now = Date.now(), future = new Date(now + 1e6).toISOString()
  assert.equal(core.orderState({ revoked: false, expires_at: future, downloads: 0, max_downloads: 5 }, now), 'ok')
  assert.equal(core.orderState({ revoked: true, expires_at: future, downloads: 0, max_downloads: 5 }, now), 'revoked')
  assert.equal(core.orderState({ revoked: false, expires_at: new Date(now - 1).toISOString(), downloads: 0, max_downloads: 5 }, now), 'expired')
  assert.equal(core.orderState({ revoked: false, expires_at: future, downloads: 5, max_downloads: 5 }, now), 'used')
  assert.equal(new Date(core.orderExpiry(500, 0)).getTime(), 90 * 86_400_000)
})
test('delivery email: escaped, has link, limits and no tracking; gated off by default', () => {
  const m = core.renderDelivery({ storeName: 'Jane <b>', productTitle: 'Guide "1"', accent: '#e50914', url: 'https://saasnation.site/d/abc', files: [{ name: '<x>.pdf', size_bytes: 2048 }], maxDownloads: 5, expiresAt: '2026-11-04T00:00:00Z', supportEmail: 'help@example.com' })
  assert.match(m.html, /https:\/\/saasnation\.site\/d\/abc/); assert.doesNotMatch(m.html, /<b>|<x>/); assert.match(m.html, /up to 5 downloads/)
  assert.doesNotMatch(m.html, /<img|pixel|open\.gif/i); assert.match(m.text, /Get your files: https:\/\/saasnation\.site\/d\/abc/)
  assert.equal(deliveryGate({ demo: false, sellerOn: true, env: {} }).ok, false)
  assert.equal(deliveryGate({ demo: false, sellerOn: true, env: { DOWNLOADS_SEND_ENABLED: '1' } }).ok, false) // no Resend key
  assert.equal(deliveryGate({ demo: false, sellerOn: false, env: { DOWNLOADS_SEND_ENABLED: '1', RESEND_API_KEY: 'x' } }).ok, false)
  assert.equal(deliveryGate({ demo: true, sellerOn: true, env: { DOWNLOADS_SEND_ENABLED: '1', RESEND_API_KEY: 'x' } }).ok, false)
  assert.equal(deliveryGate({ demo: false, sellerOn: true, env: { DOWNLOADS_SEND_ENABLED: 'true', RESEND_API_KEY: 'x' } }).ok, true)
  assert.equal(deliveryFrom('Jane "<x>"', {}), '"Jane x via SaaS Nation" <downloads@saasnation.site>')
  assert.equal(core.sendingEnvEnabled({}), false)
})
