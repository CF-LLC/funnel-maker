test('migration: additive, RLS on every table, private bucket, no anon storage policy, counter is service-only, flag OFF', () => {
  const sql = read('supabase/migrations/20261028a_downloads.sql')
  assert.doesNotMatch(sql, /drop table|truncate|delete from|drop policy/i)
  for (const t of ['dl_stores', 'dl_products', 'dl_files', 'dl_orders']) assert.match(sql, new RegExp(`alter table public\\.${t} enable row level security`))
  assert.match(sql, /security definer set search_path = public/)
  assert.doesNotMatch(sql, /on storage\.objects for \w+ to (anon|public)/)
  assert.match(sql, /grant execute on function public\.dl_take_download\(uuid, uuid\) to service_role/)
  assert.match(sql, /revoke all on function public\.dl_take_download\(uuid, uuid\) from public, anon, authenticated/)
  assert.match(sql, /\('downloads_public', false/)
  assert.doesNotMatch(sql.match(/grant select \(([^)]*)\) on public\.dl_orders/)[1], /token/)
})
