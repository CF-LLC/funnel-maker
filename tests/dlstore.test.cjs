test('file rules: type from extension, 50 MB cap, empty rejected', () => {
  assert.deepEqual(core.checkFile('Guide.PDF', 1000), { ok: true, mime: 'application/pdf', name: 'Guide.PDF' })
  assert.equal(core.checkFile('course.zip', 49 * 1024 * 1024).mime, 'application/zip')
  assert.equal(core.checkFile('x.exe', 10).ok, false)
  assert.equal(core.checkFile('noext', 10).ok, false)
  assert.equal(core.checkFile('a.pdf', 0).ok, false)
  assert.equal(core.checkFile('a.pdf', 50 * 1024 * 1024 + 1).ok, false)
  assert.equal(core.checkFile('evil.html', 10).ok, false)
  assert.equal(core.checkFile('evil.svg', 10).ok, false)
})
